fn to_kbps(s: &str) -> u64 {
    let s = s.trim().to_uppercase();
    if s.ends_with("M") {
        let n: f64 = s.trim_end_matches("M").parse().unwrap_or(0.0);
        (n * 1000.0) as u64
    } else if s.ends_with("K") {
        let n: f64 = s.trim_end_matches("K").parse().unwrap_or(0.0);
        n as u64
    } else {
        s.parse().unwrap_or(0)
    }
}

fn ip_to_minors(ip: &str) -> (u16, u16) {
    let last: u16 = ip.rsplit('.').next()
        .and_then(|s| s.parse().ok())
        .unwrap_or(1);
    (1000 + last * 2, 1000 + last * 2 + 1)
}

/// Aplica QoS en interfaz PPP — usa pppN (IP puro, sin encapsulación)
/// DOWN en egress de pppN (trafico server→cliente), UP en egress de ifb_pppN (trafico cliente→server via ingress redirect)
/// FIX 2026-08-02: rate (garantizado) y ceil (máximo) SEPARADOS del VSA
/// "rate_up/rate_down ceil_up/ceil_down". Antes el ceil se usaba como rate
/// (clase rate==ceil) — ahora se respeta exactamente lo del RADIUS.
fn apply_qos_ppp(client_ip: &str, ppp_iface: &str, speed_up: &str, speed_down: &str, up_ceil_str: &str, down_ceil_str: &str) {
    // NOTA: El QoS se aplica POR CLIENTE en su interfaz pppN individual.
    // NO limitar en WAN (eth0/eth1/eth2) porque hay balanceo de carga
    // (MWAN activo). Cada cliente PPP tiene su propio arbol HTB en pppN
    // (DOWN egress) y su propio ifb_pppN (UP via ingress redirect).
    // Esto funciona independientemente de por que WAN salga el trafico.
    if speed_up.is_empty() || speed_down.is_empty() { return; }
    let up_kbps = to_kbps(speed_up);
    let down_kbps = to_kbps(speed_down);
    if up_kbps == 0 && down_kbps == 0 { return; }
    // Ceil (máximo): si el RADIUS lo manda se usa; sino ceil = rate
    let up_ceil_kbps = if up_ceil_str.is_empty() { up_kbps } else { to_kbps(up_ceil_str) };
    let down_ceil_kbps = if down_ceil_str.is_empty() { down_kbps } else { to_kbps(down_ceil_str) };

    eprintln!("[PPP-QOS] {client_ip}@{ppp_iface}: up={speed_up}({up_kbps}kbps/ceil={up_ceil_kbps}kbps) down={speed_down}({down_kbps}kbps/ceil={down_ceil_kbps}kbps)");

    let (down_min, up_min) = ip_to_minors(client_ip);
    let down_cid = format!("1:{down_min}");
    let up_cid = format!("1:{up_min}");
    let ifb_name = format!("ifb_{ppp_iface}");

    // Limpiar estado previo en pppN (DOWN) y en ifb (UP)
    // PRIO UNICO POR CLIENTE (100+last_octet): con prio 1 compartido el del
    // operaba sobre el primer filtro del bucket, que podia ser de otro cliente.
    let prio = format!("{}", 100 + (down_min - 1000) / 2);
    let _ = Command::new("tc").args(["filter", "del", "dev", ppp_iface, "parent", "1:0", "protocol", "ip", "prio", &prio,
        "u32", "match", "ip", "dst", client_ip, "flowid", &down_cid]).output();
    let _ = Command::new("tc").args(["class", "del", "dev", ppp_iface, "classid", &down_cid]).output();

    let _ = Command::new("tc").args(["filter", "del", "dev", &ifb_name, "parent", "1:0", "protocol", "ip", "prio", &prio,
        "u32", "match", "ip", "src", client_ip, "flowid", &up_cid]).output();
    let _ = Command::new("tc").args(["class", "del", "dev", &ifb_name, "classid", &up_cid]).output();

    // Garantizar arbol HTB root en pppN con default class
    let out = Command::new("tc").args(["class", "show", "dev", ppp_iface, "classid", "1:1"]).output();
    let has_class1 = out.map(|o| String::from_utf8_lossy(&o.stdout).contains("htb")).unwrap_or(false);
    if !has_class1 {
        let _ = Command::new("tc").args(["qdisc", "add", "dev", ppp_iface, "root", "handle", "1:", "htb", "default", "2"]).output();
        let _ = Command::new("tc").args(["class", "add", "dev", ppp_iface, "parent", "1:", "classid", "1:1", "htb", "rate", "100mbit"]).output();
        let _ = Command::new("tc").args(["class", "add", "dev", ppp_iface, "parent", "1:1", "classid", "1:2", "htb", "rate", "100mbit", "ceil", "100mbit", "burst", "64k", "cburst", "64k"]).output();
    }

    // Preparar ifb_pppN para UP (crear si no existe, levantar, luego construir arbol HTB)
    let _ = Command::new("ip").args(["link", "add", &ifb_name, "type", "ifb"]).output();
    let _ = Command::new("ip").args(["link", "set", &ifb_name, "up"]).output();
    // rp_filter=2 (loose) necesario porque IFB no participa en tabla de ruteo
    let _ = Command::new("sysctl").args(["-w", &format!("net.ipv4.conf.{}.rp_filter=2", &ifb_name)]).output();
    let _ = Command::new("sysctl").args(["-w", &format!("net.ipv4.conf.{}.rp_filter=2", ppp_iface)]).output();

    // Garantizar arbol HTB root en ifb_pppN para UP (trafico cliente→server)
    let out2 = Command::new("tc").args(["class", "show", "dev", &ifb_name, "classid", "1:1"]).output();
    let has_ifb_htb = out2.map(|o| String::from_utf8_lossy(&o.stdout).contains("htb")).unwrap_or(false);
    if !has_ifb_htb {
        let _ = Command::new("tc").args(["qdisc", "add", "dev", &ifb_name, "root", "handle", "1:", "htb", "default", "2"]).output();
        let _ = Command::new("tc").args(["class", "add", "dev", &ifb_name, "parent", "1:", "classid", "1:1", "htb", "rate", "100mbit"]).output();
        let _ = Command::new("tc").args(["class", "add", "dev", &ifb_name, "parent", "1:1", "classid", "1:2", "htb", "rate", "100mbit", "ceil", "100mbit", "burst", "64k", "cburst", "64k"]).output();
    }

    // Garantizar ingress qdisc + redirect en pppN hacia ifb_pppN
    let has_ingress = Command::new("tc").args(["qdisc", "show", "dev", ppp_iface, "parent", "ffff:"]).output()
        .map(|o| String::from_utf8_lossy(&o.stdout).contains("ingress")).unwrap_or(false);
    if !has_ingress {
        let _ = Command::new("tc").args(["qdisc", "add", "dev", ppp_iface, "ingress"]).output();
    }

    // Redirigir ingress de pppN a ifb_pppN (solo si no existe ya)
    let has_redirect = Command::new("tc").args(["filter", "show", "dev", ppp_iface, "parent", "ffff:"]).output()
        .map(|o| String::from_utf8_lossy(&o.stdout).contains(&ifb_name)).unwrap_or(false);
    if !has_redirect {
        let _ = Command::new("tc").args(["filter", "add", "dev", ppp_iface, "parent", "ffff:", "protocol", "all",
            "u32", "match", "u32", "0", "0", "action", "mirred", "egress", "redirect", "dev", &ifb_name]).output();
    }

    // Burst proporcional: 100ms de datos para buena performance TCP
    let down_burst = format!("{}b", std::cmp::min(std::cmp::max(down_kbps * 125, 16000), 131072));
    let up_burst = format!("{}b", std::cmp::min(std::cmp::max(up_kbps * 125, 16000), 131072));

    let down_ceil = std::cmp::min(down_ceil_kbps, 100000);
    let up_ceil = std::cmp::min(up_ceil_kbps, 100000);

    // Clase DOWN en pppN egress (match dst IP = servidor→cliente)
    if down_kbps > 0 {
        let changed = Command::new("tc").args(["class", "change", "dev", ppp_iface, "classid", &down_cid, "htb",
            "rate", &format!("{}kbit", down_kbps), "ceil", &format!("{}kbit", down_ceil),
            "burst", &down_burst, "cburst", &down_burst]).output()
            .map(|o| o.status.success()).unwrap_or(false);
        if !changed {
            let _ = Command::new("tc").args(["class", "add", "dev", ppp_iface, "parent", "1:1", "classid", &down_cid, "htb",
                "rate", &format!("{}kbit", down_kbps), "ceil", &format!("{}kbit", down_ceil),
                "burst", &down_burst, "cburst", &down_burst]).output();
        }
        let _ = Command::new("tc").args(["filter", "add", "dev", ppp_iface, "parent", "1:0", "protocol", "ip", "prio", &prio,
            "u32", "match", "ip", "dst", client_ip, "flowid", &down_cid]).output();
    }

    // Clase UP en ifb_pppN egress (match src IP = cliente→servidor via ingress redirect)
    if up_kbps > 0 {
        let changed = Command::new("tc").args(["class", "change", "dev", &ifb_name, "classid", &up_cid, "htb",
            "rate", &format!("{}kbit", up_kbps), "ceil", &format!("{}kbit", up_ceil),
            "burst", &up_burst, "cburst", &up_burst]).output()
            .map(|o| o.status.success()).unwrap_or(false);
        if !changed {
            let _ = Command::new("tc").args(["class", "add", "dev", &ifb_name, "parent", "1:1", "classid", &up_cid, "htb",
                "rate", &format!("{}kbit", up_kbps), "ceil", &format!("{}kbit", up_ceil),
                "burst", &up_burst, "cburst", &up_burst]).output();
        }
        let _ = Command::new("tc").args(["filter", "add", "dev", &ifb_name, "parent", "1:0", "protocol", "ip", "prio", &prio,
            "u32", "match", "ip", "src", client_ip, "flowid", &up_cid]).output();
    }
}

/// POST /api/ppp/qos/radius — llamado por ip-up cuando RADIUS está activo.
/// Lee /var/run/radattr.pppN (escrito por radattr.so) y extrae la VSA MikroTik
/// rate-limit (oui 14988, vt 8/53) con el MISMO formato que hotspot:
/// "rate_up/rate_down ceil_up/ceil_down" → aplica QoS tc.
pub async fn qos_radius_apply(Json(body): Json<HashMap<String, String>>) -> Result<Json<Value>, (StatusCode, String)> {
    let username = body.get("username").cloned().unwrap_or_default();
    let client_ip = body.get("ip").cloned().unwrap_or_default();
    let ppp_iface = body.get("iface").cloned().unwrap_or_default();
    if client_ip.is_empty() || ppp_iface.is_empty() {
        return Err((StatusCode::BAD_REQUEST, "ip and iface required".into()));
    }

    let radattr_path = format!("/var/run/radattr.{ppp_iface}");
    let radattr = std::fs::read_to_string(&radattr_path).unwrap_or_default();

    // Auto-registro del cliente desde la conexion (FIX 2026-08-02):
    // si el username no existe en secrets JSON se agrega con la IP del RADIUS
    auto_register_from_connection(&username, &client_ip);

    // Buscar linea "26:<hex>" (Vendor-Specific) o nombre directo
    // "Mikrotik-Rate-Limit <valor>" — radattr.so escribe las VSAs que
    // CONOCE por nombre (dictionary de radiusclient): los MS-MPPE se ven
    // como "MS-MPPE-Recv-Key ..."; con Mikrotik en el dictionary la VSA
    // llega como "Mikrotik-Rate-Limit 1M/4M 2M/5M". El "26:<hex>" queda
    // como fallback para diccionarios que no la conocen.
    let mut raw_rate: Option<String> = None;
    for line in radattr.lines() {
        let line = line.trim();
        if let Some(rest) = line.strip_prefix("Mikrotik-Rate-Limit") {
            let v = rest.trim();
            if !v.is_empty() {
                raw_rate = Some(v.to_string());
                break;
            }
        }
        if !line.starts_with("26:") { continue; }
        let hexpart = line[3..].trim();
        // radattr escribe el value completo del attr 26 como hex:
        // vendor-id(4) + vendor-type(1) + vendor-len(1) + data
        let bytes = hex_to_bytes(hexpart);
        if bytes.len() >= 6 {
            let oui = u32::from_be_bytes([bytes[0], bytes[1], bytes[2], bytes[3]]);
            if oui == 14988 {
                let vt = bytes[4];
                let vl = bytes[5] as usize;
                if (vt == 8 || vt == 53) && 6 + vl <= bytes.len() {
                    if let Ok(s) = std::str::from_utf8(&bytes[6..6 + vl]) {
                        raw_rate = Some(s.trim().to_string());
                        break;
                    }
                }
            }
        }
    }

    let Some(raw) = raw_rate else {
        // Sin VSA rate-limit: solo RADIUS (perfiles locales eliminados) -> sin QoS
        return Ok(Json(serde_json::json!({"status": "ok", "qos": "no rate-limit in radattr"})));
    };

    // Parse formato Zpot: "rate_up/rate_down ceil_up/ceil_down"
    let tokens: Vec<&str> = raw.split_whitespace().collect();
    let (mut speed_up, mut speed_down, mut up_ceil, mut down_ceil) = (String::new(), String::new(), String::new(), String::new());
    if let Some(t0) = tokens.first() {
        if t0.contains('/') {
            let p: Vec<&str> = t0.split('/').collect();
            speed_up = p[0].to_string();
            if p.len() >= 2 { speed_down = p[1].to_string(); }
            if tokens.len() >= 2 {
                let c: Vec<&str> = tokens[1].split('/').collect();
                up_ceil = c[0].to_string();
                if c.len() >= 2 { down_ceil = c[1].to_string(); }
            }
        } else {
            speed_up = t0.to_string();
            if tokens.len() >= 2 { speed_down = tokens[1].to_string(); }
        }
    }

    if speed_up.is_empty() && speed_down.is_empty() {
        return Ok(Json(serde_json::json!({"status": "ok", "qos": "empty rate-limit"})));
    }

    eprintln!("[PPP-RADIUS-QOS] {username}@{ppp_iface} ip={client_ip} raw={raw} -> up={speed_up} down={speed_down} ceil_up={up_ceil} ceil_down={down_ceil}");

    // Aplicar QoS con rate y ceil separados (transparente: respeta el VSA)
    apply_qos_ppp(&client_ip, &ppp_iface, &speed_up, &speed_down, &up_ceil, &down_ceil);

    Ok(Json(serde_json::json!({
        "status": "ok", "qos": "applied-radius", "raw": raw,
        "speed_up": speed_up, "speed_down": speed_down,
        "ceil_up": up_ceil, "ceil_down": down_ceil,
    })))
}

/// POST /api/ppp/qos/cleanup — llamado por ip-down al desconectarse.
/// Limpia clases/filtros tc de la interfaz (best-effort; ip-down ademas
/// elimina la interfaz con ip link delete, lo que borra su arbol tc).
pub async fn qos_cleanup(Json(body): Json<HashMap<String, String>>) -> Json<Value> {
    let client_ip = body.get("ip").cloned().unwrap_or_default();
    let ppp_iface = body.get("iface").cloned().unwrap_or_default();
    if client_ip.is_empty() || ppp_iface.is_empty() {
        return Json(serde_json::json!({"ok": true, "cleanup": "no-op"}));
    }
    let (down_min, up_min) = ip_to_minors(&client_ip);
    let prio = format!("{}", 100 + (down_min - 1000) / 2);
    let _ = Command::new("tc").args(["filter", "del", "dev", &ppp_iface, "parent", "1:0", "protocol", "ip", "prio", &prio,
        "u32", "match", "ip", "dst", &client_ip, "flowid", &format!("1:{down_min}")]).output();
    let _ = Command::new("tc").args(["class", "del", "dev", &ppp_iface, "classid", &format!("1:{down_min}")]).output();
    // P2: limpiar TAMBIEN el filtro UP en ifb_pppN y ELIMINAR el ifb
    // (leak — antes el ifb_pppN quedaba para siempre)
    let ifb = format!("ifb_{}", ppp_iface);
    let up_prio = format!("{}", 100 + (up_min - 1000) / 2);
    let _ = Command::new("tc").args(["filter", "del", "dev", &ifb, "parent", "1:0", "protocol", "ip", "prio", &up_prio,
        "u32", "match", "ip", "src", &client_ip, "flowid", &format!("1:{up_min}")]).output();
    let _ = Command::new("tc").args(["class", "del", "dev", &ifb, "classid", &format!("1:{up_min}")]).output();
    let _ = Command::new("ip").args(["link", "del", "dev", &ifb]).output();
    eprintln!("[PPP-CLEANUP] {}@{} limpiado (ifb {} eliminado)", client_ip, ppp_iface, ifb);
    Json(serde_json::json!({"ok": true, "cleanup": "done", "ifb": ifb}))
}

fn hex_to_bytes(s: &str) -> Vec<u8> {
    let s: String = s.chars().filter(|c| c.is_ascii_hexdigit()).collect();
    let mut out = Vec::with_capacity(s.len() / 2);
    let bytes = s.as_bytes();
    let mut i = 0;
    while i + 1 < bytes.len() {
        if let (Some(h), Some(l)) = (hex_nibble(bytes[i]), hex_nibble(bytes[i + 1])) {
            out.push(h * 16 + l);
        }
        i += 2;
    }
    out
}

fn hex_nibble(b: u8) -> Option<u8> {
    match b {
        b'0'..=b'9' => Some(b - b'0'),
        b'a'..=b'f' => Some(b - b'a' + 10),
        b'A'..=b'F' => Some(b - b'A' + 10),
        _ => None,
    }
}

