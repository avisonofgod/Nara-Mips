/// POST /api/ppp/server/start — arranca pppoe-server si no corre (idempotente)
pub async fn pppoe_start() -> Json<Value> {
    // P1: pool parametrizado desde ppp-radius.json (antes -R hardcodeado
    // 192.168.20.100 -N 100 — la UI pool_start/pool_end no se aplicaba)
    let mut args = String::from("-I eth4.881 -m 1412 -q /usr/sbin/pppd -L 192.168.20.1");
    let cfg = super::ppp_radius::load_config();
    let pool_start = cfg.pool_start.trim().to_string();
    let pool_end = cfg.pool_end.trim().to_string();
    let count = pool_start.parse::<u32>().ok()
        .zip(pool_end.parse::<u32>().ok())
        .map(|(s, e)| if e >= s { e - s + 1 } else { 0 })
        .unwrap_or(0);
    if count > 0 && !pool_start.is_empty() {
        args.push_str(&format!(" -R {} -N {}", pool_start, count));
    } else {
        args.push_str(" -R 192.168.20.100 -N 100");
    }
    let script = format!(
        "pgrep -f '[p]ppoe-server -I' >/dev/null || setsid {} {} >/dev/null 2>&1 &",
        PPPOE_SERVER_BIN, args
    );
    let _ = Command::new("/bin/sh").args(["-c", &script]).output();
    tokio::time::sleep(std::time::Duration::from_millis(300)).await;
    pppoe_status().await
}

/// POST /api/ppp/server/stop — detiene pppoe-server (impide nuevas conexiones)
/// Nota: las sesiones PPP activas quedan huérfanas hasta que el CPE reconecte.
pub async fn pppoe_stop() -> Json<Value> {
    let _ = Command::new("/bin/sh")
        .args(["-c", "pkill -f '[p]ppoe-server -I' || true"])
        .output();
    tokio::time::sleep(std::time::Duration::from_millis(300)).await;
    pppoe_status().await
}
