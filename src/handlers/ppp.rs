const SECRETS_JSON_PATH: &str = "/etc/zpot-ppp-secrets.json";

// P1: lock de secrets — serializa load-modify-save (sync 60s vs handlers)
// para que un borrado/reorden no se pierda ni "resucite"
static SECRETS_LOCK: std::sync::Mutex<()> = std::sync::Mutex::new(());

#[derive(Debug, Serialize, Deserialize, Clone)]
pub struct PppSecret {
    #[serde(default)]
    pub id: u32, // ID unico por cliente (1..n); reutiliza huecos al eliminar filas
    pub username: String,
    pub password: String,
    #[serde(default = "default_iface")]
    pub interface: String,
    #[serde(default = "default_ip")]
    pub ip: String,
    pub profile: String,
    #[serde(default)]
    pub enabled: bool,
    #[serde(default)]
    pub caller_id: String,
}

fn default_iface() -> String { "*".to_string() }
fn default_ip() -> String { "*".to_string() }

// Secrets — JSON + chap-secrets

/// Menor entero positivo no usado como id (reutiliza huecos al eliminar filas).
fn next_free_id(secrets: &[PppSecret]) -> u32 {
    let mut used: Vec<u32> = secrets.iter().map(|s| s.id).filter(|i| *i > 0).collect();
    used.sort_unstable();
    let mut candidate = 1u32;
    for u in used {
        if u == candidate { candidate += 1; }
        else if u > candidate { break; }
    }
    candidate
}

/// Asigna id a los secretos con id==0 usando el menor libre (en orden de
/// aparicion). Devuelve true si hubo cambios. Migra clientes viejos.
fn assign_missing_ids(secrets: &mut Vec<PppSecret>) -> bool {
    let mut used: Vec<u32> = secrets.iter().map(|s| s.id).filter(|i| *i > 0).collect();
    let mut changed = false;
    for s in secrets.iter_mut() {
        if s.id == 0 {
            let mut candidate = 1u32;
            while used.contains(&candidate) { candidate += 1; }
            s.id = candidate;
            used.push(candidate);
            changed = true;
        }
    }
    changed
}

fn load_secrets_json() -> Vec<PppSecret> {
    let mut secrets: Vec<PppSecret> = fs::read_to_string(SECRETS_JSON_PATH)
        .ok()
        .and_then(|s| serde_json::from_str(&s).ok())
        .unwrap_or_default();
    // Migracion: asignar id a clientes sin id (1..n en orden, reutiliza huecos)
    if assign_missing_ids(&mut secrets) {
        save_secrets_to_disk(&secrets);
        eprintln!("[PPP-SECRETS] ids asignados a {} clientes", secrets.len());
    }
    secrets
}

/// Persiste secrets JSON + regenera /etc/ppp/chap-secrets (fallback local).
/// FIX 2026-08-02: usado por el auto-registro desde la conexion PPP.
fn save_secrets_to_disk(secrets: &[PppSecret]) {
    // 1. JSON
    if let Some(parent) = std::path::Path::new(SECRETS_JSON_PATH).parent() {
        let _ = fs::create_dir_all(parent);
    }
    if let Ok(json) = serde_json::to_string_pretty(secrets) {
        // P1: escritura atomica (tmp+rename) — antes fs::write directo
        let tmp = format!("{}.tmp-{}", SECRETS_JSON_PATH, std::process::id());
        let _ = fs::write(&tmp, &json);
        let _ = fs::rename(&tmp, SECRETS_JSON_PATH);
    }
    // 2. chap-secrets (formato: client, server, secret, IP)
    let mut cs = String::from("# Generated by Zpot-RS\n");
    for s in secrets {
        if !s.enabled { continue; }
        // P1: NUNCA usar el username como password (auth local bypass).
        // Sin password local (auto-registro MSCHAPv2) → secret ALEATORIO
        // que no coincide con nada → la auth local falla para esos users
        // (correcto: no tienen password local; su auth es RADIUS).
        let secret = if s.password.is_empty() {
            let nanos = std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .map(|d| d.subsec_nanos())
                .unwrap_or(0);
            format!("zp-{:x}{:x}", std::process::id(), nanos)
        } else {
            s.password.clone()
        };
        let ip = if s.ip.is_empty() || s.ip == "*" { "*" } else { &s.ip };
        cs.push_str(&format!("{}\t*\t{}\t{}\n", s.username, secret, ip));
    }
    let _ = fs::write("/etc/ppp/chap-secrets", cs.as_bytes());
}

/// Auto-registro de cliente PPP desde la conexion (FIX 2026-08-02):
/// si el username NO existe en secrets JSON, se agrega con la IP que dio
/// el RADIUS (Framed-IP del Access-Accept). El password NO esta disponible
/// en la conexion (MSCHAPv2 solo transmite hash) -> queda vacio.
/// Si ya existe: solo se completa la IP si esta vacia o "*" (no se
/// sobreescriben IPs estaticas asignadas manualmente).
fn auto_register_from_connection(username: &str, client_ip: &str) -> bool {
    if username.is_empty() || client_ip.is_empty() { return false; }
    let _g = SECRETS_LOCK.lock().unwrap_or_else(|e| e.into_inner());
    let mut secrets = load_secrets_json();
    let exists = secrets.iter().any(|s| s.username.eq_ignore_ascii_case(username));
    if exists {
        // Completar IP solo si falta
        let mut changed = false;
        for s in secrets.iter_mut() {
            if s.username.eq_ignore_ascii_case(username) && (s.ip.is_empty() || s.ip == "*") {
                s.ip = client_ip.to_string();
                changed = true;
            }
        }
        if changed {
            save_secrets_to_disk(&secrets);
            eprintln!("[PPP-AUTOREG] {} IP completada a {}", username, client_ip);
            return true;
        }
        return false;
    }
    secrets.push(PppSecret {
        id: next_free_id(&secrets),
        username: username.to_string(),
        password: String::new(),
        interface: "*".to_string(),
        ip: client_ip.to_string(),
        profile: "ClientesPPP".to_string(),
        enabled: true,
        caller_id: String::new(),
    });
    save_secrets_to_disk(&secrets);
    eprintln!("[PPP-AUTOREG] Nuevo cliente agregado: {} ip={}", username, client_ip);
    true
}

pub async fn secrets_list() -> Result<Json<Vec<PppSecret>>, (StatusCode, String)> {
    // P2: enmascarar passwords — el SPA no necesita el password real
    // (ninguna pagina lo usa; evita exponer secretos en la UI)
    let mut secrets = load_secrets_json();
    for s in &mut secrets {
        if !s.password.is_empty() {
            s.password = "***".to_string();
        }
    }
    Ok(Json(secrets))
}

/// POST /api/ppp/secrets — crea o actualiza (upsert por username).
/// P2: antes NO existia API para crear/editar secretos (solo list/delete/
/// order/disconnect). El password "***" (enmascarado) conserva el actual.
pub async fn secrets_upsert(Json(mut body): Json<PppSecret>) -> Result<Json<serde_json::Value>, (StatusCode, String)> {
    let username = body.username.trim().to_string();
    if username.is_empty() {
        return Err((StatusCode::BAD_REQUEST, "username requerido".into()));
    }
    if username.chars().any(|c| c.is_control()) {
        return Err((StatusCode::BAD_REQUEST, "username con caracteres de control".into()));
    }
    if body.password == "***" {
        body.password.clear(); // conservar el actual (se rellena abajo)
    }
    if body.ip.is_empty() {
        body.ip = "*".to_string();
    }
    if !body.ip.is_empty() && body.ip != "*" && body.ip.parse::<std::net::Ipv4Addr>().is_err() {
        return Err((StatusCode::BAD_REQUEST, format!("ip invalida: {}", body.ip)));
    }

    let _g = SECRETS_LOCK.lock().unwrap_or_else(|e| e.into_inner());
    let mut secrets = load_secrets_json();
    let existing = secrets.iter_mut().find(|s| s.username.eq_ignore_ascii_case(&username));
    match existing {
        Some(s) => {
            // conservar el password actual si el body no trae uno nuevo
            if body.password.is_empty() {
                body.password = s.password.clone();
            }
            *s = body;
            s.username = username.clone();
        }
        None => {
            let id = next_free_id(&secrets);
            body.id = id;
            body.username = username.clone();
            secrets.push(body);
        }
    }
    save_secrets_to_disk(&secrets);
    Ok(Json(serde_json::json!({"ok": true, "username": username})))
}

async fn disconnect_user(username: &str) -> Result<String, String> {
    // Correlacion SIN depender del syslog (se pierde con rotacion):
    //   username -> IP (secrets JSON)
    //   IP -> interfaz pppN (ip -json addr, campo "address" = peer)
    //   pppN -> MAC (/var/run/ppp-mac-pppN) -> pppd PID (remotenumber)
    // OJO: el comando viejo usaba `pkill -f '^pppd'` = mataba TODOS los pppd.
    let secrets = load_secrets_json();
    let Some(ip) = secrets.iter()
        .find(|s| s.username.eq_ignore_ascii_case(username))
        .and_then(|s| if s.ip.is_empty() || s.ip == "*" { None } else { Some(s.ip.clone()) })
    else { return Ok(String::new()); };

    let out = tokio::process::Command::new("/bin/sh")
        .args(["-c", "ip -json addr show type ppp 2>/dev/null || echo '[]'"])
        .output().await.ok();
    let Some(out) = out else { return Ok(String::new()); };
    let links: Vec<serde_json::Value> = serde_json::from_slice(&out.stdout).unwrap_or_default();
    let mut intf = String::new();
    for link in &links {
        let peer = link["addr_info"].as_array()
            .and_then(|a| a.get(0))
            .and_then(|a| a["address"].as_str())
            .unwrap_or("");
        if peer == ip {
            if let Some(n) = link["ifname"].as_str() {
                intf = n.to_string();
            }
        }
    }
    if intf.is_empty() { return Ok(String::new()); }

    // Matar SOLO el pppd de esa interfaz (por MAC del peer en su cmdline)
    // OJO: /proc/PID/cmdline separa args con \0 -> convertir a espacios antes
    // de grep (mismo truco que el ip-up). Raw string: sin escapes Rust.
    let kill_cmd = format!(r#"mac=$(cat /var/run/ppp-mac-{intf} 2>/dev/null | tr -d ' \n'); [ -z "$mac" ] && exit 1; for pid in $(pgrep -x pppd 2>/dev/null); do if grep -q "remotenumber $mac" <(tr '\0' ' ' < /proc/$pid/cmdline) 2>/dev/null; then kill $pid 2>/dev/null; exit 0; fi; done; exit 1"#);
    // P1: verificar el RESULTADO del kill — antes `let _` ignoraba el fallo
    // y respondia "disconnected" aunque el pppd siguiera vivo (falso exito)
    let kill_out = tokio::process::Command::new("/bin/sh").args(["-c", &kill_cmd]).output().await
        .map_err(|e| e.to_string())?;
    if !kill_out.status.success() {
        return Err(format!("no se pudo matar el pppd de {}", intf));
    }
    Ok(intf)
}

pub async fn secrets_disconnect(Json(body): Json<serde_json::Value>) -> Result<Json<serde_json::Value>, (StatusCode, String)> {
    let username = body["username"].as_str().ok_or((StatusCode::BAD_REQUEST, "username required".to_string()))?;
    match disconnect_user(username).await {
        Ok(intf) if intf.is_empty() => Ok(Json(serde_json::json!({"ok": true, "message": "no active session"}))),
        Ok(intf) => Ok(Json(serde_json::json!({"ok": true, "disconnected": intf}))),
        Err(e) => Err((StatusCode::BAD_REQUEST, e)),
    }
}

/// POST /api/ppp/secrets/delete — elimina un secreto del JSON (y regenera
/// chap-secrets). El id queda LIBRE: el proximo cliente sin registro (o el
/// sync) lo reutiliza via next_free_id.
pub async fn secrets_delete(Json(body): Json<serde_json::Value>) -> Json<serde_json::Value> {
    let username = body["username"].as_str().unwrap_or("").trim().to_string();
    if username.is_empty() {
        return Json(serde_json::json!({"ok": false, "error": "username required"}));
    }
    let _g = SECRETS_LOCK.lock().unwrap_or_else(|e| e.into_inner());
    let mut secrets = load_secrets_json();
    let before = secrets.len();
    secrets.retain(|s| !s.username.eq_ignore_ascii_case(&username));
    if secrets.len() == before {
        return Json(serde_json::json!({"ok": true, "message": "no existe"}));
    }
    save_secrets_to_disk(&secrets);
    eprintln!("[PPP-SECRETS] eliminado {} (quedan {})", username, secrets.len());
    Json(serde_json::json!({"ok": true, "deleted": username, "remaining": secrets.len()}))
}

/// POST /api/ppp/secrets/order — reordena el JSON segun el array de
/// usernames recibido (drag & drop de la UI). No toca los ids.
pub async fn secrets_order(Json(body): Json<serde_json::Value>) -> Json<serde_json::Value> {
    let order: Vec<String> = body["order"].as_array()
        .map(|a| a.iter().filter_map(|v| v.as_str().map(|s| s.to_string())).collect())
        .unwrap_or_default();
    if order.is_empty() {
        return Json(serde_json::json!({"ok": false, "error": "order required"}));
    }
    let _g = SECRETS_LOCK.lock().unwrap_or_else(|e| e.into_inner());
    let mut secrets = load_secrets_json();
    let mut ordered: Vec<PppSecret> = Vec::with_capacity(secrets.len());
    for name in &order {
        if let Some(pos) = secrets.iter().position(|s| s.username.eq_ignore_ascii_case(name)) {
            ordered.push(secrets.remove(pos));
        }
    }
    ordered.extend(secrets); // los que no estaban en el order (nuevos) al final
    save_secrets_to_disk(&ordered);
    eprintln!("[PPP-SECRETS] orden actualizado ({} filas)", ordered.len());
    Json(serde_json::json!({"ok": true, "count": ordered.len()}))
}

