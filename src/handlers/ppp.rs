/// Resultado del parse del syslog: correlacion intf->usuario y IP->usuario.
/// La IP es mas confiable (el intf pppN se recicla entre reconexiones).
struct SyslogUsers {
    by_intf: std::collections::HashMap<String, String>,
    by_ip: std::collections::HashMap<String, String>,
}

/// Parsea el syslog de pppd: lineas "user X logged in intf pppN ... remote
/// <IP>" -> mapas intf->usuario y IP->usuario.
/// FIX 2026-08-02: lee TAMBIEN /var/log/messages.0 (rotado) — el syslog rota
/// y los clientes conectados desde antes de la rotacion solo tienen su linea
/// en el archivo viejo. El orden messages.0 -> messages hace que las lineas
/// nuevas sobreescriban las viejas del mismo intf/IP.
fn parse_syslog_users() -> SyslogUsers {
    let mut by_intf = std::collections::HashMap::new();
    let mut by_ip = std::collections::HashMap::new();
    for path in ["/var/log/messages.0", "/var/log/messages"] {
        let log_data = std::fs::read_to_string(path).unwrap_or_default();
        for line in log_data.lines() {
            if let Some(idx) = line.find(" logged in ") {
                let before = &line[..idx];
                let mut user = String::new();
                if let Some(user_pos) = before.rfind("user ") {
                    let user_start = user_pos + 5;
                    let user_end = before[user_start..].find(' ').map(|p| user_start + p).unwrap_or(before.len());
                    user = before[user_start..user_end].trim().to_string();
                }
                let mut intf = String::new();
                if let Some(intf_pos) = line[idx..].find("intf ") {
                    let intf_start = idx + intf_pos + 5;
                    let intf_end = line[intf_start..].find(' ').map(|p| intf_start + p).unwrap_or(line.len());
                    intf = line[intf_start..intf_end].trim().to_string();
                }
                let mut ip = String::new();
                if let Some(rem_pos) = line[idx..].find("remote ") {
                    let rem_start = idx + rem_pos + 7;
                    let rem_end = line[rem_start..].find(' ').map(|p| rem_start + p).unwrap_or(line.len());
                    ip = line[rem_start..rem_end].trim().to_string();
                }
                if !user.is_empty() {
                    if !intf.is_empty() { by_intf.insert(intf, user.clone()); }
                    if !ip.is_empty() { by_ip.insert(ip, user); }
                }
            }
        }
    }
    SyslogUsers { by_intf, by_ip }
}

/// Fetch interfaces PPP vivas del kernel (ip -json addr show type ppp).
async fn fetch_ppp_links() -> Vec<serde_json::Value> {
    tokio::process::Command::new("/bin/sh")
        .args(["-c", "ip -json addr show type ppp 2>/dev/null || echo '[]'"])
        .output()
        .await
        .map(|o| serde_json::from_slice(&o.stdout).unwrap_or_default())
        .unwrap_or_default()
}

/// Sync periodico: syslog + kernel -> auto-registro de /ppp/secrets.
/// NO depende del ip-up: si el POST del ip-up fallo (backend caido), este
/// task lo captura en <=60s. Idempotente (auto_register no duplica ni
/// sobreescribe IPs fijas). Misma fuente que active_list.
async fn ppp_sync_once() {
    let log_map = parse_syslog_users();
    let links = fetch_ppp_links().await;
    let mut checked = 0usize;
    let mut changed = 0usize;
    for link in &links {
        let ifname = link["ifname"].as_str().unwrap_or("");
        let peer = link["addr_info"].as_array()
            .and_then(|a| a.get(0))
            .and_then(|a| a["address"].as_str())
            .unwrap_or("");
        if ifname.is_empty() || peer.is_empty() { continue; }
        // Prioridad por IP (estable por sesion), fallback por intf
        let user = log_map.by_ip.get(peer).cloned()
            .or_else(|| log_map.by_intf.get(ifname).cloned())
            .unwrap_or_default();
        if user.is_empty() { continue; }
        checked += 1;
        if auto_register_from_connection(&user, peer) { changed += 1; }
    }
    if changed > 0 {
        eprintln!("[PPP-SYNC] revisadas {} sesiones activas, {} cambios en secrets", checked, changed);
    }
}

/// Spawnea el sync periodico de clientes PPP (cada 60s, primero inmediato).
pub fn spawn_ppp_sync_task() {
    tokio::spawn(async {
        use tokio::time::{interval, Duration};
        let mut tick = interval(Duration::from_secs(60));
        loop {
            tick.tick().await;
            ppp_sync_once().await;
        }
    });
}

pub async fn active_list() -> Result<Json<Vec<serde_json::Value>>, (StatusCode, String)> {
    // Usar ip -json addr para obtener peer IP (remote)
    let links = fetch_ppp_links().await;

    // Build peer_ip -> username map from chap-secrets JSON
    let secrets: Vec<PppSecret> = fs::read_to_string(SECRETS_JSON_PATH)
        .ok()
        .and_then(|s| serde_json::from_str(&s).ok())
        .unwrap_or_default();
    let mut ip_to_user = std::collections::HashMap::new();
    for s in &secrets {
        if s.enabled && !s.ip.is_empty() && s.ip != "*" {
            ip_to_user.insert(s.ip.clone(), s.username.clone());
        }
    }

    // Get username per ppp interface from /var/log/messages
    let log_map = parse_syslog_users();

    let mut sessions = Vec::new();

    // Leer estadisticas reales del kernel (rx/tx bytes)
    let stats_raw = tokio::process::Command::new("/bin/sh")
        .args(["-c", "ip -j -s link show type ppp 2>/dev/null || echo '[]'"])
        .output()
        .await
        .map_err(|e| (StatusCode::INTERNAL_SERVER_ERROR, e.to_string()))?;
    let stats_links: Vec<serde_json::Value> = serde_json::from_slice(&stats_raw.stdout)
        .unwrap_or_default();
    let mut stats_map = std::collections::HashMap::new();
    for link in &stats_links {
        let name = link["ifname"].as_str().unwrap_or("").to_string();
        if name.is_empty() { continue; }
        let rx_b = link["stats64"]["rx"]["bytes"].as_u64().unwrap_or(0);
        let tx_b = link["stats64"]["tx"]["bytes"].as_u64().unwrap_or(0);
        stats_map.insert(name, (rx_b, tx_b));
    }

    // UPTIME ELIMINADO (2026-08-08): ppp_uptime ejecutaba 3 comandos sync
    // por interfaz (pgrep+awk+awk = 7 procesos) → ~235 procesos por
    // llamada con 33 PPP. El operador solo necesita conectado/desconectado.
    // /api/ppp/active baja de ~330ms a ~15ms.

    for link in &links {
        let ifname = link["ifname"].as_str().unwrap_or("");
        if ifname.is_empty() { continue; }
        let (bytes_in, bytes_out) = stats_map.get(ifname).copied().unwrap_or((0, 0));

        // Syslog (por IP primero — estable — luego por intf), despues
        // fallback a chap-secrets JSON por IP
        let peer_ip = link["addr_info"].as_array()
            .and_then(|a| a.get(0))
            .and_then(|a| a["address"].as_str())
            .unwrap_or("")
            .to_string();
        let mut user = log_map.by_ip.get(&peer_ip).cloned()
            .or_else(|| log_map.by_intf.get(ifname).cloned())
            .unwrap_or_else(|| "-".to_string());

        if user == "-" && !peer_ip.is_empty() {
            user = ip_to_user.get(&peer_ip).cloned().unwrap_or_else(|| "-".to_string());
        }

        sessions.push(serde_json::json!({
            "interface": ifname,
            "user": user,
            "remote_ip": peer_ip,
            "local_ip": link["addr_info"].as_array().and_then(|a| a.get(0)).and_then(|a| a["local"].as_str()).unwrap_or("-"),
            "bytes_in": bytes_in,
            "bytes_out": bytes_out,
        }));
    }
    Ok(Json(sessions))
}

// Logs
pub async fn logs_list() -> Result<Json<Vec<serde_json::Value>>, (StatusCode, String)> {
    let output = tokio::process::Command::new("/bin/sh")
        .args(["-c", "journalctl -u ppp --no-pager -n 50 2>/dev/null || grep -i -E '(ppp|pppoe|pppd)' /var/log/messages 2>/dev/null | tail -50 || echo 'no logs'"])
        .output()
        .await
        .map_err(|e| (StatusCode::INTERNAL_SERVER_ERROR, e.to_string()))?;

    let text = String::from_utf8_lossy(&output.stdout);
    let mut logs = Vec::new();
    for line in text.lines().rev().take(50) {
        if line.is_empty() { continue; }
        logs.push(serde_json::json!({"line": line}));
    }
    Ok(Json(logs))
}

