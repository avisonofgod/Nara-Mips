/// POST /api/ip/remote — actualiza la IP destino del DNAT
/// Acceso remoto generico: puerto 8082 del servidor -> <ip>:80 del cliente
/// (vale para IPs Hotspot eth3 192.168.10.x y PPPoE eth3.881 192.168.20.x).
/// SIN iifname: el DNAT aplica por cualquier interfaz (wg0 VPN, eth1 internet).
/// ip vacio = DESACTIVAR (borra las reglas nft y el archivo de estado).
pub async fn remote_set(Json(body): Json<HashMap<String, String>>) -> Result<Json<Value>, (StatusCode, String)> {
    let ip = body.get("ip").map(|s| s.trim().to_string()).unwrap_or_default();

    // Desactivar: eliminar reglas DNAT (8082 y 443) y estado
    if ip.is_empty() {
        cleanup_remote_rules();
        let _ = std::fs::remove_file(REMOTE_IP_FILE);
        return Ok(Json(serde_json::json!({"status": "ok", "ip": "", "port": REMOTE_PORT})));
    }

    // Validar formato IP basico
    let parts: Vec<&str> = ip.split('.').collect();
    if parts.len() != 4 || parts.iter().any(|p| p.parse::<u8>().is_err()) {
        return Err((StatusCode::BAD_REQUEST, "invalid IP format".into()));
    }
    // P1: restringir a rangos LOCALES del servidor (hotspot o PPPoE) —
    // antes aceptaba CUALQUIER IP (DNAT a internet = proxy abierto)
    let oct = parts[0].parse::<u8>().unwrap_or(0);
    let oct3 = parts[2].parse::<u8>().unwrap_or(0);
    if !(oct == 192 && parts[1] == "168" && (oct3 == 10 || oct3 == 20)) {
        return Err((StatusCode::BAD_REQUEST,
            "IP fuera de rango local (solo 192.168.10.x hotspot / 192.168.20.x PPPoE)".into()));
    }

    let dst = format!("{}:80", ip);
    let dst_https = format!("{}:443", ip);

    cleanup_remote_rules();

    // Agregar nueva regla DNAT con comentario.
    // FIX (2026-08-04): restringida a iifname { wg0, eth1 } (solo admin VPN +
    // internet). ANTES era `iifname != "lo"` -> el DNAT 443 capturaba TODO el
    // HTTPS forward de clientes PPPoE/LAN (los mandaba al panel del AP) y el
    // 8082 dejaba que cualquier cliente hotspot NO autenticado abriera el AP.
    let remote_port_str = REMOTE_PORT.to_string();
    let _ = Command::new("nft").args(["add", "rule", "inet", "hotspot", "prerouting",
        "iifname", "{ \"wg0\", \"eth1\" }", "tcp", "dport", &remote_port_str, "dnat", "ip", "to", &dst, "comment", "zpot-remote"]).output();
    // HTTPS: el panel del AP (Ubiquiti/Omada) responde 302 a https://<host>/
    // -> DNAT 443 -> <ip>:443 para que el redirect siga pasando por el servidor.
    // El cleanup (comment "zpot-remote") tambien borra esta regla (contiene el prefijo).
    let _ = Command::new("nft").args(["add", "rule", "inet", "hotspot", "prerouting",
        "iifname", "{ \"wg0\", \"eth1\" }", "tcp", "dport", "443", "dnat", "ip", "to", &dst_https, "comment", "zpot-remote-https"]).output();

    // Guardar IP actual
    let _ = std::fs::write(REMOTE_IP_FILE, ip.as_bytes());

    Ok(Json(serde_json::json!({"status": "ok", "ip": ip, "port": REMOTE_PORT})))
}

/// Borra TODAS las reglas DNAT del acceso remoto (comment zpot-remote*)
/// de la chain prerouting de la tabla hotspot.
fn cleanup_remote_rules() {
    let list_out = Command::new("nft").args(["-a", "list", "chain", "inet", "hotspot", "prerouting"]).output()
        .map(|o| String::from_utf8_lossy(&o.stdout).to_string()).unwrap_or_default();
    for line in list_out.lines() {
        if line.contains("zpot-remote") {
            // Extraer handle: "handle N" al final de la linea
            if let Some(h) = line.split_whitespace().filter_map(|w| {
                if w.starts_with("handle") { w.strip_prefix("handle ") } else { None }
            }).last().or_else(|| {
                line.rsplit(' ').filter_map(|w| w.strip_prefix("handle ")).next()
            }).or_else(|| {
                // Buscar "handle" en la linea — el formato es ...comment "zpot-remote" # handle N
                line.split('#').nth(1).and_then(|s| s.trim().strip_prefix("handle "))
                    .or_else(|| line.rsplit("handle ").nth(1).and_then(|s| s.split_whitespace().next()))
            }) {
                if let Ok(handle) = h.parse::<u64>() {
                    let _ = Command::new("nft").args(["delete", "rule", "inet", "hotspot", "prerouting", "handle", &handle.to_string()]).output();
                }
            }
            // Tambien intentar con split por #
            for part in line.split('#') {
                let trimmed = part.trim();
                if let Some(hstr) = trimmed.strip_prefix("handle ") {
                    if let Ok(handle) = hstr.parse::<u64>() {
                        let _ = Command::new("nft").args(["delete", "rule", "inet", "hotspot", "prerouting", "handle", &handle.to_string()]).output();
                    }
                }
            }
        }
    }
}

